// Regenerates src/renderer/botIconSvgs.ts from Liz's currentColor SVGs in art/v1.5/bot-icons-svg/.
// Run by hand after an art update: `node scripts/gen-bot-icon-svgs.mjs`. The output is committed, and a test
// checks it still matches the art files. The renderer inlines these trusted, bundled strings (parsed with
// DOMParser) so the chosen color applies via currentColor; nothing is ever loaded from user input.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'art/v1.5/bot-icons-svg';
const out = 'src/renderer/botIconSvgs.ts';
const ALLOWED_TAGS = new Set(['svg', 'g', 'line', 'circle', 'rect', 'polygon', 'polyline', 'path']);
const ALLOWED_ATTRS = new Set(['xmlns', 'width', 'height', 'viewBox', 'color', 'x1', 'y1', 'x2', 'y2', 'cx', 'cy', 'r',
  'x', 'y', 'rx', 'points', 'd', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity', 'transform']);

/** Throws unless the markup is plain static SVG: known shape elements and presentation attributes only. */
function assertStaticSvg(file, svg) {
  if (/<!|<\?|&|script|foreignObject|href|url\(|style|on[a-z]+\s*=/i.test(svg)) throw new Error(`${file}: not plain static SVG`);
  for (const [, tag, attrs] of svg.matchAll(/<\/?([a-zA-Z]+)([^>]*)>/g)) {
    if (!ALLOWED_TAGS.has(tag)) throw new Error(`${file}: element <${tag}> not allowed`);
    for (const [, name] of attrs.matchAll(/([a-zA-Z-:]+)\s*=/g)) if (!ALLOWED_ATTRS.has(name)) throw new Error(`${file}: attribute ${name} not allowed`);
  }
}

const files = readdirSync(dir).filter((f) => /^cipher-bot-\d\d-[a-z]+\.svg$/.test(f)).sort();
const entries = files.map((f) => {
  const svg = readFileSync(join(dir, f), 'utf8').trim();
  assertStaticSvg(f, svg);
  return [f.replace(/^cipher-bot-\d\d-|\.svg$/g, ''), svg];
});
// v2 (animated avatars): split each icon into named parts so the renderer can animate them separately.
// Rules (match Liz's files): the element filled #15171c is the body; before it, 5px lines and r=7 rings are the
// side ports and anything else is decoration (antenna, chip pins, monitor stand); after it, r=8.5 circles are
// the eyes and the rest is the mouth. The parts also go to art/v2/bot-avatars-svg/ as grouped, classed SVGs.
const PART_KEYS = ['deco', 'ports', 'body', 'eyes', 'mouth'];
function splitParts(file, svg) {
  const els = [...svg.matchAll(/<(line|circle|rect|polygon|polyline|path)\b[^>]*\/>/g)].map((m) => m[0]);
  const bodyAt = els.findIndex((e) => /fill="#15171c"/.test(e));
  if (bodyAt < 0) throw new Error(`${file}: no body (fill="#15171c")`);
  const parts = { deco: [], ports: [], body: [els[bodyAt]], eyes: [], mouth: [] };
  els.forEach((e, i) => {
    if (i < bodyAt) (/^<line[^>]*stroke-width="5"/.test(e) || /^<circle[^>]*\br="7"/.test(e) ? parts.ports : parts.deco).push(e);
    else if (i > bodyAt) (/^<circle[^>]*\br="8\.5"/.test(e) ? parts.eyes : parts.mouth).push(e);
  });
  if (parts.eyes.length !== 2 || !parts.mouth.length) throw new Error(`${file}: expected two eyes and a mouth`);
  return parts;
}
const parted = entries.map(([k, svg], i) => [k, splitParts(files[i], svg)]);
const v2dir = 'art/v2/bot-avatars-svg';
mkdirSync(v2dir, { recursive: true });
parted.forEach(([k, p], i) => {
  const g = PART_KEYS.map((key) => `<g class="${key}">${p[key].join('')}</g>`).join('');
  writeFileSync(join(v2dir, files[i]), `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" color="#22C8E8">${g}</svg>\n`);
});
const partsBody = parted.map(([k, p]) => `  ${k}: { ${PART_KEYS.map((key) => `${key}: ${JSON.stringify(p[key].join(''))}`).join(', ')} },`).join('\n');
const body = entries.map(([k, svg]) => `  ${k}: ${JSON.stringify(svg)},`).join('\n');
writeFileSync(out, `// GENERATED by scripts/gen-bot-icon-svgs.mjs from art/v1.5/bot-icons-svg/ (Liz's v1.5 icons). Do not edit.
// Plain static SVG drawn in currentColor (dark #15171c body): checked for scripts, external refs and styles.

export const BOT_SHAPE_SVGS = {
${body}
} as const;

/** The same icons split into named parts for the animated avatar (see avatar.ts). Static shape markup only. */
export interface BotShapeParts { deco: string; ports: string; body: string; eyes: string; mouth: string }
export const BOT_SHAPE_PARTS: Record<keyof typeof BOT_SHAPE_SVGS, BotShapeParts> = {
${partsBody}
};
`);
console.log(`wrote ${out} (${entries.length} shapes) and ${v2dir}/`);
