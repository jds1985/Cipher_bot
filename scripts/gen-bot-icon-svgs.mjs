// Regenerates src/renderer/botIconSvgs.ts from Liz's currentColor SVGs in art/v1.5/bot-icons-svg/.
// Run by hand after an art update: `node scripts/gen-bot-icon-svgs.mjs`. The output is committed, and a test
// checks it still matches the art files. The renderer inlines these trusted, bundled strings (parsed with
// DOMParser) so the chosen color applies via currentColor; nothing is ever loaded from user input.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'art/v1.5/bot-icons-svg';
const out = 'src/renderer/botIconSvgs.ts';
const ALLOWED_TAGS = new Set(['svg', 'g', 'line', 'circle', 'rect', 'polygon', 'polyline', 'path']);
const ALLOWED_ATTRS = new Set(['xmlns', 'width', 'height', 'viewBox', 'color', 'x1', 'y1', 'x2', 'y2', 'cx', 'cy', 'r',
  'x', 'y', 'rx', 'points', 'd', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity', 'transform']);

/** Throws unless the markup is plain static SVG: known shape elements and presentation attributes only. */
function assertStaticSvg(file, svg) {
  if (/<!|<\?|&|script|foreignObject|href|url\(|style|on[a-z]+\s*=/i.test(svg)) throw new Error(`${file}: not plain static SVG`);
  for (const [, tag, attrs] of svg.matchAll(/<\/?([a-zA-Z]+)([^>]*)>/g)) {
    if (!ALLOWED_TAGS.has(tag)) throw new Error(`${file}: element <${tag}> not allowed`);
    for (const [, name] of attrs.matchAll(/([a-zA-Z-:]+)\s*=/g)) if (!ALLOWED_ATTRS.has(name)) throw new Error(`${file}: attribute ${name} not allowed`);
  }
}

const files = readdirSync(dir).filter((f) => /^cipher-bot-\d\d-[a-z]+\.svg$/.test(f)).sort();
const entries = files.map((f) => {
  const svg = readFileSync(join(dir, f), 'utf8').trim();
  assertStaticSvg(f, svg);
  return [f.replace(/^cipher-bot-\d\d-|\.svg$/g, ''), svg];
});
const body = entries.map(([k, svg]) => `  ${k}: ${JSON.stringify(svg)},`).join('\n');
writeFileSync(out, `// GENERATED by scripts/gen-bot-icon-svgs.mjs from art/v1.5/bot-icons-svg/ (Liz's v1.5 icons). Do not edit.
// Plain static SVG drawn in currentColor (dark #15171c body): checked for scripts, external refs and styles.

export const BOT_SHAPE_SVGS = {
${body}
} as const;
`);
console.log(`wrote ${out} (${entries.length} shapes)`);
