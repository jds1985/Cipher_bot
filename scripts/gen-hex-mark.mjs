// Copies the Cipher Hex Circuit mark (art/brand/hex_circuit*.svg, from /workspace/brand) verbatim into src/shared/hexMark.ts.
// The drone composer places these exact paths in the Cipher eye; only the gradient id is swapped per drone.
import { readFileSync, writeFileSync } from 'node:fs';
const read = (f) => { const s = readFileSync(f, 'utf8');
  const stops = s.match(/<linearGradient[^>]*>([\s\S]*?)<\/linearGradient>/)[1];
  const grad = s.match(/<linearGradient ([^>]*)>/)[1].replace(/id="g" ?/, '');
  const body = s.replace(/^[\s\S]*?<\/defs>/, '').replace(/<\/svg>\s*$/, '').replaceAll('url(#g)', '{G}');
  return { grad, stops, body }; };
const out = `// GENERATED by scripts/gen-hex-mark.mjs from art/brand/hex_circuit.svg and hex_circuit_small.svg. Do not edit by hand.
// 64x64 mark space. {G} is replaced with the drone's gradient url.
export const HEX_MARK = ${JSON.stringify(read('art/brand/hex_circuit.svg'), null, 1)} as const;
export const HEX_MARK_SMALL = ${JSON.stringify(read('art/brand/hex_circuit_small.svg'), null, 1)} as const;
`;
writeFileSync('src/shared/hexMark.ts', out); console.log('wrote src/shared/hexMark.ts');
