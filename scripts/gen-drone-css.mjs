// Regenerates the palette block of src/renderer/drone.css from DRONE_PALETTES (run after `npm run build`).
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
copyFileSync('dist/shared/hexMark.js', '/tmp/hexMark.js'); copyFileSync('dist/shared/droneParts.js', '/tmp/droneParts.mjs');
writeFileSync('/tmp/droneParts.mjs', readFileSync('/tmp/droneParts.mjs', 'utf8').replace("'./hexMark.js'", "'./hexMark.mjs'"));
copyFileSync('dist/shared/hexMark.js', '/tmp/hexMark.mjs');
const { DRONE_PALETTES } = await import('/tmp/droneParts.mjs');
const T = ['body', 'deep', 'hi', 'glow', 'glow2', 'metal'];
let b = '/* BEGIN palettes (generated by scripts/gen-drone-css.mjs) */\n';
for (const t of T) b += `.drone .dr-f-${t} { fill: var(--d-${t}, var(--dp-${t})); } .drone .dr-k-${t} { stroke: var(--d-${t}, var(--dp-${t})); } .drone .dr-s-${t} { stop-color: var(--d-${t}, var(--dp-${t})); }\n`;
for (const [k, p] of Object.entries(DRONE_PALETTES)) b += `.drone.pal-${k} { ${T.map((t) => `--dp-${t}: ${p[t]};`).join(' ')} }\n`;
for (const [k, p] of Object.entries(DRONE_PALETTES)) b += `.dr-swatch.pal-${k} { background: radial-gradient(circle at 35% 30%, ${p.hi}, ${p.body} 45%, ${p.deep}); box-shadow: inset 0 0 0 2px ${p.glow}55; }\n`;
b += '/* END palettes */';
const f = 'src/renderer/drone.css'; let css = readFileSync(f, 'utf8');
css = /\/\* BEGIN palettes[\s\S]*END palettes \*\//.test(css) ? css.replace(/\/\* BEGIN palettes[\s\S]*END palettes \*\//, b) : css.trimEnd() + '\n\n' + b + '\n';
writeFileSync(f, css); console.log('updated', f);
